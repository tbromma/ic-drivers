#pragma once
#include "common.h"
#include "rv3028Types.h"

/******************************************************************************************************************************************
                                                                    API
******************************************************************************************************************************************/
namespace drv {

class RV3028 {
public:

    using I2cTxPoll_t = Exec (*)(uint8 slaveAddr, uint8* txData, uint8 txSize);
    using I2cTxRxPoll_t = Exec (*)(uint8 slaveAddr, uint8* txSrc, uint8 txSize, uint8* rxDest, uint8 rxSize);
    using I2cGetStatus_t = Status (*)();

    struct config_t {
        uint8           i2cAddr = rv3028::I2C_ADDR;
        I2cTxPoll_t     I2cTxPoll = nullptr;
        I2cTxRxPoll_t   I2cTxRxPoll = nullptr;
        I2cGetStatus_t  I2cGetStatus = nullptr;
        const char*     label_p = nullptr;
    };

    Exec  Setup(const config_t& config);
    Exec  ReadRegister(rv3028::RegAddr regAddr, uint8& regVal);
    Exec  WriteRegister(rv3028::RegAddr regAddr, uint8 regVal);
    Exec  ReadMultipleRegs(rv3028::RegAddr regStart, uint8* regData, uint8 byteCnt);
    Exec  WriteMultipleRegs(rv3028::RegAddr regStart, uint8* regData, uint8 byteCnt);
    Status  GetStatus();

private:

    struct {
        config_t    config = {};
        Status      status = Status::NONE;
    } ctx = {};
};

} // End of namespace 'drv'
